/* Build-time sync for the homepage's static content:
   1. Converged hljs markup -> React string + index.html skeleton (byte-identical)
   2. LQIP blur-up placeholder for the profile photo -> img tag in React + skeleton

   The converged markup is the exact hljs output the old runtime produced
   (extracted once from the live DOM). To change site content, edit
   src/Intro.converged.html directly (or re-derive via browser + hljs).

   The LQIP is a ~25px blurred WebP of public/profile.png, base64-inlined
   (<1KB) so first paint shows a blurry version of the real photo instead
   of an empty box. Generated automatically from the source image, so it
   can never go stale.

   Run: node scripts/generate.mjs */
import { readFileSync, writeFileSync } from 'fs';
import { execSync } from 'child_process';
import { tmpdir } from 'os';
import { join } from 'path';

// ---------- 1) Converged hljs markup ----------
const converged = readFileSync('src/Intro.converged.html', 'utf8');

if (!converged.includes('hljs-section') || !converged.includes('<h1>')) {
  throw new Error('src/Intro.converged.html does not look like converged hljs markup');
}

writeFileSync(
  'src/Intro.highlighted.ts',
  `// AUTO-GENERATED by scripts/generate.mjs from src/Intro.converged.html — do not edit\n` +
    `const IntroHighlighted = ${JSON.stringify(converged)};\n\n` +
    `export default IntroHighlighted;\n`
);

// ---------- 2) LQIP placeholder ----------
// 24px wide, quality 30 -> a few hundred bytes, blurred by CSS at render size.
const tmpOut = join(tmpdir(), `lqip-${process.pid}.webp`);
execSync(`cwebp -quiet -resize 24 0 -q 30 public/profile.png -o ${tmpOut}`);
const lqipBytes = readFileSync(tmpOut);
const lqip = `data:image/webp;base64,${lqipBytes.toString('base64')}`;

writeFileSync(
  'src/ProfileLqip.ts',
  `// AUTO-GENERATED by scripts/generate.mjs from public/profile.png — do not edit\n` +
    `const ProfileLqip = ${JSON.stringify(lqip)};\n\n` +
    `export default ProfileLqip;\n`
);

// ---------- 3) Sync skeleton in index.html ----------
let index = readFileSync('index.html', 'utf8');

// 3a) text block
const openTag = '<div class="Hero"><pre class="markdown hljs"><code class="markdown hljs">';
const skeletonStart = index.indexOf(openTag);
if (skeletonStart === -1) throw new Error('Skeleton block not found in index.html');
const contentStart = skeletonStart + openTag.length;
const contentEnd = index.indexOf('</code></pre></div>', contentStart);
if (contentEnd === -1) throw new Error('Skeleton end tag not found');
index = index.slice(0, contentStart) + converged + index.slice(contentEnd);

// 3b) profile img src -> LQIP data URI in the skeleton (real image via JS swap).
//     Idempotent: matches either the original /profile.png form or a previous
//     LQIP run (src is regenerated either way).
let indexNew;
const plainMarker = '<img src="/profile.png" alt="Profile" width="500" height="750" />';
const lqipRe = /<img src="data:image\/webp;base64,[A-Za-z0-9+/=]+" alt="Profile" width="500" height="750" data-src="\/profile\.png" \/>/;
const plainIdx = index.indexOf(plainMarker);
const lqipMatch = index.match(lqipRe);
const replacement = `<img src="${lqip}" alt="Profile" width="500" height="750" data-src="/profile.png" />`;
if (plainIdx !== -1) {
  indexNew = index.slice(0, plainIdx) + replacement + index.slice(plainIdx + plainMarker.length);
} else if (lqipMatch) {
  indexNew = index.replace(lqipRe, replacement);
} else {
  throw new Error('Skeleton profile img not found');
}
index = indexNew;

writeFileSync('index.html', index);

console.log('generate.mjs:',
  'converged', converged.length, 'chars;',
  'LQIP', lqipBytes.length, 'bytes inline;',
  'React + skeleton synced');